// Bundles the Factory (Droid) capture plugin into a committed text module.
//
//   node scripts/bundle-factory-plugin.mjs           regenerate the module
//   node scripts/bundle-factory-plugin.mjs --check   exit 1 when the committed module is stale
//
// The plugin ships as TEXT inside the KyberDash bundle (npm and SEA alike), the way the
// OpenCode plugin does, because a runtime file asset would not exist inside the SEA.
//
// The Factory plugin is a hook SCRIPT, not a module a host imports: Factory runs the file as
// a command and hands it the hook payload on stdin. The bundle entry therefore calls the
// one-shot runner and lets it resolve; the runner always exits 0, because a capture plugin
// must never fail the host that ran it.
//
// A plugin tree cannot resolve `node_modules`, so the bundle is self-contained: esbuild inlines
// every local module and only `node:` built-ins stay external.
//
// esbuild is the bundler tsup already uses; it is a direct devDependency so this script does not
// rely on tsup hoisting it.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

/** First line of the bundle; the ownership marker the installer checks. */
export const FACTORY_PLUGIN_MARKER = '// kyberdash-factory-plugin v1'

const dashRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pluginDir = join(dashRoot, 'src', 'capture', 'harnesses', 'factory-plugin')
export const GENERATED_FILE = join(pluginDir, 'generated', 'plugin-source.ts')

/** Bundle the one-shot hook runner to one ESM string with `node:` built-ins left external. */
export async function bundleFactoryPlugin() {
  const result = await build({
    stdin: {
      contents: "import { runHook } from './entry.js'\nawait runHook()\n",
      resolveDir: pluginDir,
      sourcefile: 'factory-plugin-bundle-entry.ts',
      loader: 'ts',
    },
    absWorkingDir: dashRoot,
    bundle: true,
    write: false,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    minify: false,
    sourcemap: false,
    legalComments: 'none',
    banner: { js: FACTORY_PLUGIN_MARKER },
    logLevel: 'silent',
  })
  const output = result.outputFiles?.[0]
  if (result.outputFiles?.length !== 1 || output === undefined) {
    throw new Error(`factory plugin bundle: expected one output file, got ${result.outputFiles?.length ?? 0}`)
  }
  return output.text
}

/** The TypeScript text of the generated module for a bundle string. */
export function renderPluginSourceModule(source) {
  return [
    FACTORY_PLUGIN_MARKER,
    '// GENERATED by scripts/bundle-factory-plugin.mjs. Do not edit; run `node scripts/bundle-factory-plugin.mjs`.',
    '// The Factory (Droid) capture plugin as text (plan D13). The installer writes it into the owned plugin tree.',
    '',
    `export const FACTORY_PLUGIN_MARKER = ${JSON.stringify(FACTORY_PLUGIN_MARKER)}`,
    '',
    `export const FACTORY_PLUGIN_SOURCE = ${JSON.stringify(source)}`,
    '',
  ].join('\n')
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const expected = renderPluginSourceModule(await bundleFactoryPlugin())
  if (process.argv.includes('--check')) {
    let current
    try {
      current = readFileSync(GENERATED_FILE, 'utf8')
    } catch {
      current = undefined
    }
    if (current !== expected) {
      process.stderr.write('factory plugin source is stale; run `node scripts/bundle-factory-plugin.mjs`\n')
      process.exit(1)
    }
  } else {
    writeFileSync(GENERATED_FILE, expected)
  }
}
