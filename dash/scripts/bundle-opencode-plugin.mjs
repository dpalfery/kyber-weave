// Bundles the OpenCode capture plugin (plan D3) into a committed text module.
//
//   node scripts/bundle-opencode-plugin.mjs           regenerate the module
//   node scripts/bundle-opencode-plugin.mjs --check   exit 1 when the committed module is stale
//
// The plugin ships as TEXT inside the KyberDash bundle (npm and SEA alike), the way the Kilo
// plugin does, because a runtime file asset would not exist inside the SEA. OpenCode 2.1.4 reads
// only `.default` and requires `{ id, setup }`, so a stdin entry re-exports `default` alone:
// `entry.ts` also exports `createSetup`, which must not reach the loader.
//
// esbuild is the bundler tsup already uses; it is a direct devDependency so this script does not
// rely on tsup hoisting it.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

/** First line of the bundle; the ownership marker the installer (T4) checks. */
export const OPENCODE_PLUGIN_MARKER = '// kyberdash-opencode-plugin v1'

const dashRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pluginDir = join(dashRoot, 'src', 'capture', 'harnesses', 'opencode-plugin')
export const GENERATED_FILE = join(pluginDir, 'generated', 'plugin-source.ts')

/** Bundle `entry.ts`'s default export to one ESM string with `node:` built-ins left external. */
export async function bundleOpencodePlugin() {
  const result = await build({
    stdin: {
      contents: "export { default } from './entry.js'\n",
      resolveDir: pluginDir,
      sourcefile: 'opencode-plugin-bundle-entry.ts',
      loader: 'ts',
    },
    absWorkingDir: dashRoot,
    bundle: true,
    write: false,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    minify: false,
    sourcemap: false,
    legalComments: 'none',
    banner: { js: OPENCODE_PLUGIN_MARKER },
    logLevel: 'silent',
  })
  const output = result.outputFiles?.[0]
  if (result.outputFiles?.length !== 1 || output === undefined) {
    throw new Error(`opencode plugin bundle: expected one output file, got ${result.outputFiles?.length ?? 0}`)
  }
  return output.text
}

/** The TypeScript text of the generated module for a bundle string. */
export function renderPluginSourceModule(source) {
  return [
    '// GENERATED by scripts/bundle-opencode-plugin.mjs. Do not edit; run `npm run bundle:opencode-plugin`.',
    '// The OpenCode capture plugin as text (plan D3). bundle.test.ts fails when this drifts from entry.ts.',
    '',
    `export const OPENCODE_PLUGIN_MARKER = ${JSON.stringify(OPENCODE_PLUGIN_MARKER)}`,
    '',
    `export const OPENCODE_PLUGIN_SOURCE = ${JSON.stringify(source)}`,
    '',
  ].join('\n')
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const expected = renderPluginSourceModule(await bundleOpencodePlugin())
  if (process.argv.includes('--check')) {
    let current
    try {
      current = readFileSync(GENERATED_FILE, 'utf8')
    } catch {
      current = undefined
    }
    if (current !== expected) {
      process.stderr.write('opencode plugin source is stale; run `npm run bundle:opencode-plugin`\n')
      process.exit(1)
    }
  } else {
    writeFileSync(GENERATED_FILE, expected)
  }
}
