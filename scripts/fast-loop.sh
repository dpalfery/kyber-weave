#!/usr/bin/env bash
# The fast local inner loop. Answers "did this edit break something" in seconds.
#
#   scripts/fast-loop.sh                  # fast tier (~29s on macOS when measured; re-measure after regenerating)
#   scripts/fast-loop.sh --class Docs*    # one area
#   scripts/fast-loop.sh --method <FQN>   # one test
#   scripts/fast-loop.sh --full           # the declared gate suite, unchanged
#
# WHY THIS IS NOT A THINNER `review gates`
#
# ADR 0005 already separated "did this edit break something" from "may the change be
# committed", but only on the reviewer side. It rejected a gate subset outright, for a
# reason that still holds: a review citing a hand-picked subset is citing evidence it
# selected. So the declared suite stays whole, and this script is a different instrument
# that must never be cited as review evidence. `--full` runs the real thing.
#
# THE PARTITION — measured, not guessed
#
# A per-test timing run (`-xml`) gives 477s of summed test time across 123 classes and 2655
# cases; the whole suite takes ~47s wall clock on macOS because xUnit runs classes in
# parallel. The fast tier keeps the fastest classes up to a 150s summed-time budget.
#
# The excluded classes are the slow `Squad*` and `Utilities*` lifecycle, CLI, path-safety
# and pack classes plus SquadDeploymentStateTests, which is the slowest class and has a
# lease test with a fixed 5-second wait that flakes on a loaded machine; its root cause is
# not reproduced (docs/todo/squad-lease-contention-cross-process.md).
#
# WHY EXCLUDE BY CLASS LIST RATHER THAN BY TRAIT
#
# Traits are the better long-term axis and there is exactly one in the suite today
# (`Category=Scale`). But a trait left off a new slow class fails open — the new class
# silently lands in the fast tier. A generated class list is derived from measurement
# instead of memory. See `scripts/fast-loop-classes.txt`, regenerated by `--regenerate`.
#
# WHAT MAKES THE EXCLUDED CLASSES SLOW
#
# Not process spawning: it is filesystem work, chiefly path canonicalisation that lists
# every ancestor directory (cost scales with how crowded $TMPDIR is) and per-file fsync.
# Tests now skip fsync (SquadTestDurability) and the lookup is cheaper, which took the
# full suite from ~14 minutes to ~89s. Keep $TMPDIR clean; a crowded one slows these again.

set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${repo_root}"

CONFIGURATION=Release
TEST_DLL="tests/KyberWeave.Tests/bin/${CONFIGURATION}/net10.0/KyberWeave.Tests.dll"
CLASS_LIST="scripts/fast-loop-classes.txt"

step() { printf '\n=== %s ===\n' "$1"; }

# Regenerate the fast-tier class list from a fresh timing run. Takes ~90s, so it
# is a deliberate act rather than something the loop does on its own. Re-run it when a
# class is added, renamed, or found to have gotten materially slower.
# Pass an existing timings XML (`--regenerate path.xml`) to skip the collection run.
if [[ "${1:-}" == "--regenerate" ]]; then
  timings="${2:-}"
  if [[ -z "${timings}" ]]; then
    step "collecting per-test timings (this takes ~90 seconds)"
    timings="$(mktemp "${TMPDIR:-/tmp}/kw-timings.XXXXXX")"
    dotnet "${TEST_DLL}" -xml "${timings}" >/dev/null
  fi
  python3 - "${timings}" "${CLASS_LIST}" <<'PY'
import sys, xml.etree.ElementTree as ET
from collections import defaultdict
timings, out_path = sys.argv[1], sys.argv[2]
budget = 150.0  # summed test seconds; xUnit parallelism makes wall clock ~8x smaller
by_class = defaultdict(float)
for case in ET.parse(timings).getroot().iter('test'):
    try:
        seconds = float(case.get('time') or 0)
    except ValueError:
        seconds = 0.0
    by_class[case.get('type') or '?'] += seconds
total, kept, running = sum(by_class.values()), [], 0.0
for name, seconds in sorted(by_class.items(), key=lambda kv: kv[1]):
    if running + seconds > budget:
        break
    running += seconds
    kept.append(name)
with open(out_path, 'w') as handle:
    handle.write('\n'.join(kept) + '\n')
print(f"kept {len(kept)}/{len(by_class)} classes "
      f"({running:.1f}s of {total:.0f}s summed test time)")
PY
  exit 0
fi

# --full keeps the declared suite whole. It is the merge question, and it runs everything.
if [[ "${1:-}" == "--full" ]]; then
  step "full declared gate suite"
  exec dotnet run --project src/KyberWeave.Cli -c "${CONFIGURATION}" -- \
    review gates . --out artifacts/gates.json
fi

# Parse and validate arguments before the build so a typo fails before the (slower) build.
test_args=()
case "${1:-}" in
  --class)  test_args+=(-class "${2:?--class needs a pattern}") ;;
  --method) test_args+=(-method "${2:?--method needs a fully-qualified name}") ;;
  "") ;;
  *) printf 'unknown option: %s\n' "$1" >&2; exit 2 ;;
esac

if [[ ${#test_args[@]} -eq 0 ]]; then
  while IFS= read -r class || [[ -n "${class}" ]]; do
    class="${class%$'\r'}"
    [[ -z "${class}" || "${class}" == \#* ]] && continue
    test_args+=(-class "${class}")
  done < "${CLASS_LIST}"
  if [[ ${#test_args[@]} -eq 0 ]]; then
    printf 'no classes in %s; run --regenerate\n' "${CLASS_LIST}" >&2
    exit 1
  fi
  # The scale envelope is a size-stress test, not an edit check; keep it out even if its class
  # ever lands in the generated list.
  test_args+=(-trait- "Category=Scale")
  step "tests (fast tier: $(wc -l < "${CLASS_LIST}" | tr -d ' ') classes)"
else
  step "tests (filtered)"
fi

step "build (Release, warnings-as-errors, AnalysisMode=all, --no-incremental)"
dotnet build KyberWeave.sln -c "${CONFIGURATION}" --no-incremental

# A filter that matches nothing exits 0, which reads as a pass, so read the runner's own total.
test_log="$(mktemp "${TMPDIR:-/tmp}/kw-fast-loop.XXXXXX")"
trap 'rm -f "${test_log}"' EXIT
dotnet "${TEST_DLL}" "${test_args[@]}" | tee "${test_log}"
if ! sed $'s/\x1b\\[[0-9;]*m//g' "${test_log}" | grep -Eq 'Total: [1-9][0-9]*,'; then
  printf 'no tests ran; check the --class / --method filter\n' >&2
  exit 1
fi

step "docs validate (no CodeGraph index required)"
dotnet run --project src/KyberWeave.Cli -c "${CONFIGURATION}" --no-build -- \
  docs validate .

step "format (whitespace)"
dotnet format KyberWeave.sln whitespace --verify-no-changes --no-restore -v minimal

printf '\nFast tier clean. Run scripts/fast-loop.sh --full before pushing.\n'