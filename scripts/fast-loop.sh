#!/usr/bin/env bash
# The fast local inner loop. Answers "did this edit break something" in seconds.
#
#   scripts/fast-loop.sh                  # component-aware fast checks based on changed files
#   scripts/fast-loop.sh --touched        # only the product test classes that name a changed file's types
#   scripts/fast-loop.sh --class 'KyberWeave.Tests.Area*'  # one area (.NET); the pattern matches the full name
#   scripts/fast-loop.sh --method <FQN>   # one test (.NET)
#   scripts/fast-loop.sh --full           # the declared gate suite, all gates (--all); not for dev agents
#   scripts/fast-loop.sh --scoped         # declared gate suite scoped to changed files; not for dev agents
#
# WHY THIS IS NOT A THINNER `review gates`
#
# ADR 0005 already separated "did this edit break something" from "may the change be
# committed", but only on the reviewer side. It rejected a gate subset outright, for a
# reason that still holds: a review citing a hand-picked subset is citing evidence it
# selected. So the declared suite stays whole, and this script is a different instrument
# that must never be cited as review evidence. `--full` runs the real thing.
#
# THE PARTITION — measured, not guessed
#
# The partition comes from a per-test timing run (`-xml`). The last full one (2026-11-17,
# 18 cores, load 6.7) gave 5,329s of summed test time across 538 classes and 9,840 cases,
# and 357s wall clock because xUnit runs classes in parallel. Re-measure with --regenerate
# when the suite's shape changes; the numbers here describe that run, not a target.
#
# The fast tier keeps the fastest classes up to a 150s summed-time budget.
#
# The excluded classes are the slow `Squad*` and `Utilities*` lifecycle, CLI, path-safety
# and pack classes, plus the `SquadDeploymentState*` classes that used to be one. They now
# live in tests/KyberWeave.Integration.Tests, where a real deployment is an integration test.
# Two lease tests in them wait on a fixed 5-second deadline that flakes on a loaded machine; the
# root cause is not reproduced (docs/todo/squad-lease-contention-cross-process.md).
#
# WHY EXCLUDE BY CLASS LIST RATHER THAN BY TRAIT
#
# Traits are the better long-term axis and there is exactly one in the suite today
# (`Category=Scale`). But a trait left off a new slow class fails open — the new class
# silently lands in the fast tier. A generated class list is derived from measurement
# instead of memory. See `scripts/fast-loop-classes.txt`, regenerated by `--regenerate`.
#
# tests/KyberWeave.Integration.Tests holds the tests that perform a real Squad deployment or start
# a real program. They are slower than the unit suite and run only when --touched names one of
# their classes, so an ordinary edit stays in the fast tier.
#
# THE REPOSITORY-POLICY TESTS
#
# tests/KyberWeave.RepoPolicy.Tests holds the tests whose subject is the repository itself:
# scripts, workflows, gate configuration, docs and source scans. They run here only when a
# changed file is something other than C# under src/ or a test project, with the same
# class list or filter as the product suite. A C#-only edit runs only the two policy tests that
# read source text (POLICY_SOURCE_SCANS): the rest read scripts, workflows, project files and docs.
#
# THE PROMPT-CONTENT TESTS
#
# tests/KyberWeave.PromptContent.Tests holds the tests that assert the wording of skills, agents and
# instructions. They run with the policy tests, under the same condition. The class list does not name
# them, so with no filter the whole project runs; a --class or --method filter applies to it as it does
# to the others.
#
# WHAT MAKES THE EXCLUDED CLASSES SLOW
#
# A real install or a real git repository per test, not process spawning in the abstract.
# The per-test cost is filesystem work: resolving the on-disk spelling of every path
# segment, per-file writes, and (before SquadTestDurability) fsync. Resolution no longer
# materialises a whole parent directory per segment and a deployment preflight reuses one
# listing per parent, which cut the deployment-state classes' longest span from 390s to
# 114s in a full run. What remains scales with how crowded the temp root is, so keep
# $TMPDIR clean.
#
# EVERY COMMAND RUNS DIRECTLY
#
# .NET test, build, and format steps run via `dotnet` so Roslyn/MSBuild build servers stay warm.
# KyberDash (`dash/`) and tray UI (`dash/tray/ui`) commands run via `npm --prefix ...` directly:
# KyberDash does its work in-process, so there are no recursive Node spawners to wrap or reap.
# The full-suite refusal below is this script's own: it needs no wrapper to enforce.

set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${repo_root}"

CONFIGURATION=Release
TEST_DLL="tests/KyberWeave.Tests/bin/${CONFIGURATION}/net10.0/KyberWeave.Tests.dll"
INTEGRATION_TEST_DLL="tests/KyberWeave.Integration.Tests/bin/${CONFIGURATION}/net10.0/KyberWeave.Integration.Tests.dll"
POLICY_TEST_DLL="tests/KyberWeave.RepoPolicy.Tests/bin/${CONFIGURATION}/net10.0/KyberWeave.RepoPolicy.Tests.dll"
PROMPT_TEST_DLL="tests/KyberWeave.PromptContent.Tests/bin/${CONFIGURATION}/net10.0/KyberWeave.PromptContent.Tests.dll"
# The unit projects (Application, Hooks, Kernel, Mcp, Arbiter, Cli, Data, Architecture): pure or fake-backed, so they run whole
# on every .NET loop, whatever --class / --method names a legacy project.
LAYER_TEST_DLLS=(
  "tests/KyberWeave.Application.Tests/bin/${CONFIGURATION}/net10.0/KyberWeave.Application.Tests.dll"
  "tests/KyberWeave.Hooks.Tests/bin/${CONFIGURATION}/net10.0/KyberWeave.Hooks.Tests.dll"
  "tests/KyberWeave.Kernel.Tests/bin/${CONFIGURATION}/net10.0/KyberWeave.Kernel.Tests.dll"
  "tests/KyberWeave.Mcp.Tests/bin/${CONFIGURATION}/net10.0/KyberWeave.Mcp.Tests.dll"
  "tests/KyberWeave.Arbiter.Tests/bin/${CONFIGURATION}/net10.0/KyberWeave.Arbiter.Tests.dll"
  "tests/KyberWeave.Cli.Tests/bin/${CONFIGURATION}/net10.0/KyberWeave.Cli.Tests.dll"
  "tests/KyberWeave.Data.Tests/bin/${CONFIGURATION}/net10.0/KyberWeave.Data.Tests.dll"
  "tests/KyberWeave.Architecture.Tests/bin/${CONFIGURATION}/net10.0/KyberWeave.Architecture.Tests.dll"
)
CLASS_LIST="scripts/fast-loop-classes.txt"
# The policy tests that read source text. A C#-only edit can trip them (an unlisted process
# spawn, a banned upstream name, ambient I/O in Domain), and they only read files, so they run
# on every .NET loop.
POLICY_SOURCE_SCANS=(-class KyberWeave.Tests.ProcessSpawnSitesTests -class KyberWeave.Tests.UpstreamSeveranceTests -class KyberWeave.Tests.DomainPurityTests)

step() { printf '\n=== %s ===\n' "$1"; }

test_log=""
scan_log=""
generated_timings=()
cleanup() {
  if [[ -n "${test_log:-}" && -f "${test_log}" ]]; then
    rm -f "${test_log}"
  fi
  if [[ -n "${scan_log:-}" && -f "${scan_log}" ]]; then
    rm -f "${scan_log}"
  fi
  # Only the timings files this run created; files passed to --regenerate belong to the caller.
  rm -f "${generated_timings[@]+"${generated_timings[@]}"}"
}
trap cleanup EXIT

if [[ "${1:-}" == "--help" || "${1:-}" == "-h" ]]; then
  cat <<'EOF'
Usage: scripts/fast-loop.sh [OPTIONS]

Fast local inner loop for Kyber-Weave developers.

Options:
  (no options)     Component-aware fast checks based on changed workspace files.
  --touched        Run only the product test classes that mention a type declared in a changed
                   C# file, or that sit in a changed test file. Falls back to the fast tier when
                   nothing matches or more than 40 classes match.
  --class PATTERN  Run .NET tests whose fully qualified class name matches
                   (KyberWeave.Tests.Area*). A bare Area* matches nothing.
  --method FQN     Run one specific .NET test method.
  --full           Run all declared repository gates unscoped (--all).
                   Includes the full test suite: not for dev agents.
  --scoped         Run declared repository gates scoped to changed files.
                   Runs the full product suite on a .NET change: not for dev agents.
  --regenerate [PRODUCT.xml POLICY.xml]
                   Regenerate scripts/fast-loop-classes.txt from both test projects' timings.
  --help, -h       Show this help message.

--full, --scoped and --regenerate exit 89 without running anything when stdin is not an
interactive terminal (a dev agent's shell). Run them from a terminal, or use --class / --method.
EOF
  exit 0
fi

# The full-suite modes belong to the review council and CI. A non-interactive caller (a dev agent)
# is refused with exit 89 before any build or other work; this script is the only guard the modes need.
refuse_full_suite_mode() {
  if [[ -t 0 ]]; then
    return 0
  fi
  printf 'fast-loop: refused: %s is a full test-suite run. Only the review council and CI run the full suite;\n' "$1" >&2
  printf 'fast-loop: dev agents run targeted sets instead. Use one of these:\n' >&2
  printf "fast-loop:   scripts/fast-loop.sh --class 'KyberWeave.Tests.<Area>*'\n" >&2
  printf 'fast-loop:   scripts/fast-loop.sh --method <FQN>\n' >&2
  printf 'fast-loop:   kyber-weave review gates . --agent <name>\n' >&2
  printf 'fast-loop: to run the full suite on purpose from a terminal, run this script there directly.\n' >&2
  exit 89
}

case "${1:-}" in
  --full|--scoped|--regenerate) refuse_full_suite_mode "$1" ;;
esac

# Regenerate the fast-tier class list from a fresh timing run. Takes ~90s, so it
# is a deliberate act rather than something the loop does on its own. Re-run it when a
# class is added, renamed, or found to have gotten materially slower.
# Pass existing timings XMLs, the product suite's then the policy suite's
# (`--regenerate product.xml policy.xml`), to skip the collection run.
if [[ "${1:-}" == "--regenerate" ]]; then
  timings=("${@:2}")
  # One file alone would silently drop the other project's classes from the list.
  if [[ ${#timings[@]} -ne 0 && ${#timings[@]} -ne 2 ]]; then
    printf -- '--regenerate takes no timings files, or two: the product suite'"'"'s, then the policy suite'"'"'s\n' >&2
    exit 2
  fi
  if [[ ${#timings[@]} -eq 0 ]]; then
    step "collecting per-test timings (this takes ~90 seconds)"
    timings=("$(mktemp "${TMPDIR:-/tmp}/kw-timings.XXXXXX")" "$(mktemp "${TMPDIR:-/tmp}/kw-timings.XXXXXX")")
    generated_timings=("${timings[@]}")
    # One list covers both test projects: the classes share a namespace, so a name means one test.
    dotnet "${TEST_DLL}" -xml "${timings[0]}" >/dev/null
    dotnet "${POLICY_TEST_DLL}" -xml "${timings[1]}" >/dev/null
  fi
  python3 - "${CLASS_LIST}" "${timings[@]}" <<'PY'
import sys, xml.etree.ElementTree as ET
from collections import defaultdict
out_path, timings = sys.argv[1], sys.argv[2:]
budget = 150.0  # summed test seconds; xUnit parallelism makes wall clock ~15x smaller (measured on 18 cores)
by_class = defaultdict(float)
for path in timings:
    for case in ET.parse(path).getroot().iter('test'):
        try:
            seconds = float(case.get('time') or 0)
        except ValueError:
            seconds = 0.0
        by_class[case.get('type') or '?'] += seconds
total, kept, running = sum(by_class.values()), [], 0.0
for name, seconds in sorted(by_class.items(), key=lambda kv: kv[1]):
    if running + seconds > budget:
        break
    running += seconds
    kept.append(name)
with open(out_path, 'w') as handle:
    handle.write('\n'.join(kept) + '\n')
print(f"kept {len(kept)}/{len(by_class)} classes "
      f"({running:.1f}s of {total:.0f}s summed test time)")
PY
  exit 0
fi

# --full keeps the declared suite whole. It is the merge question, and it runs everything.
if [[ "${1:-}" == "--full" ]]; then
  step "full declared gate suite"
  exec dotnet run --project src/KyberWeave.Cli -c "${CONFIGURATION}" -- \
    review gates . --all --out artifacts/gates.json
fi

# --scoped runs declared repository gates scoped to changed files against base.
if [[ "${1:-}" == "--scoped" ]]; then
  step "scoped declared gate suite"
  exec dotnet run --project src/KyberWeave.Cli -c "${CONFIGURATION}" -- \
    review gates . --out artifacts/gates.json
fi

# Parse and validate arguments before the build so a typo fails before the (slower) build.
test_args=()
integration_test_args=()
touched=0
case "${1:-}" in
  --touched) touched=1 ;;
  --class)  test_args+=(-class "${2:?--class needs a pattern}") ;;
  --method) test_args+=(-method "${2:?--method needs a fully-qualified name}") ;;
  "") ;;
  *) printf 'unknown option: %s\n' "$1" >&2; exit 2 ;;
esac

# Component routing: if --class or --method was supplied, focus on .NET and docs validate.
# Otherwise, inspect changed workspace paths to run targeted fast checks.
changed_cs=()
needs_dotnet=0
needs_dash_server=0
needs_dash=0
needs_tray_ui=0
needs_rust=0
needs_docs=0
needs_policy=0
dash_related_files=()

if [[ ${#test_args[@]} -gt 0 ]]; then
  needs_dotnet=1
  needs_docs=1
  needs_policy=1
else
  changed_files=()
  while IFS= read -r file || [[ -n "${file}" ]]; do
    [[ -z "${file}" ]] && continue
    changed_files+=("${file}")
  done < <({ git diff --name-only HEAD 2>/dev/null; git diff --name-only --cached 2>/dev/null; git ls-files --others --exclude-standard 2>/dev/null; } | sort -u)

  changed_cs=()
  for file in "${changed_files[@]+"${changed_files[@]}"}"; do
    if [[ "${file}" == *.cs && -f "${file}" ]]; then
      changed_cs+=("${file}")
    fi
  done

  if [[ ${#changed_files[@]} -eq 0 ]]; then
    needs_dotnet=1
    needs_docs=1
    needs_policy=1
  else
    for file in "${changed_files[@]+"${changed_files[@]}"}"; do
      case "$file" in
        *.md) needs_docs=1 ;;
      esac

      case "$file" in
        dash/tray/src-tauri/*)
          needs_rust=1
          ;;
        dash/tray/ui/*)
          needs_tray_ui=1
          needs_dash=1
          ;;
        dash/server/* | dash/server.tests/*)
          needs_dash_server=1
          ;;
        dash/*.md | docs/*)
          needs_docs=1
          ;;
        dash/*)
          needs_dash=1
          if [[ -f "$file" ]]; then
            case "$file" in
              *.ts|*.tsx|*.js|*.jsx|*.mjs|*.cjs)
                dash_related_files+=("${file#dash/}")
                ;;
            esac
          fi
          ;;
        README.md | CHANGELOG.md | CONTRIBUTING.md | SECURITY.md)
          needs_docs=1
          ;;
        *)
          needs_dotnet=1
          case "$file" in
            *.md | .kyber-weave/* | src/*)
              needs_docs=1
              ;;
          esac
          # A C#-only edit to product code or product tests runs only the policy source scans:
          # the rest of the policy tests read scripts, workflows, project files and docs.
          case "$file" in
            src/*.cs | tests/KyberWeave.Tests/*.cs | tests/KyberWeave.Integration.Tests/*.cs | tests/KyberWeave.Testing/*.cs | tests/KyberWeave.Kernel.Tests/*.cs | tests/KyberWeave.Mcp.Tests/*.cs | tests/KyberWeave.Arbiter.Tests/*.cs | tests/KyberWeave.Cli.Tests/*.cs | tests/KyberWeave.Data.Tests/*.cs) ;;
            *) needs_policy=1 ;;
          esac
          ;;
      esac
    done
  fi
fi

if [[ "${needs_dotnet}" -eq 1 ]]; then
  step "build (Release, warnings-as-errors, AnalysisMode=all)"
  dotnet build KyberWeave.sln -c "${CONFIGURATION}"

  # The user's filter, if any, before the class list is added: the prompt-content project takes it
  # alone, so with the class list it runs whole.
  prompt_args=("${test_args[@]+"${test_args[@]}"}")
  if [[ "${touched}" -eq 1 && ${#test_args[@]} -eq 0 ]]; then
    # A changed file's own types, found by name in the product test sources. It is a heuristic over text, not a
    # call graph: it can miss a test that reaches the type only indirectly, which is why CI still runs everything.
    touched_types=()
    for file in "${changed_cs[@]+"${changed_cs[@]}"}"; do
      while IFS= read -r type_name; do
        touched_types+=("${type_name}")
      done < <(grep -oE '^[[:space:]]*(public|internal)[[:space:]]+([a-z]+[[:space:]]+)*(class|record|struct|interface|enum)[[:space:]]+[A-Za-z0-9_]+' "${file}" | awk '{print $NF}')
    done
    touched_files=()
    for file in "${changed_cs[@]+"${changed_cs[@]}"}"; do
      case "${file}" in
        tests/KyberWeave.Tests/*.cs | tests/KyberWeave.Integration.Tests/*.cs) touched_files+=("${file}") ;;
      esac
    done
    for type_name in "${touched_types[@]+"${touched_types[@]}"}"; do
      for root in tests/KyberWeave.Tests tests/KyberWeave.Integration.Tests; do
        while IFS= read -r file; do
          touched_files+=("${file}")
        done < <(grep -rlwF --include='*.cs' -- "${type_name}" "${root}" 2>/dev/null)
      done
    done
    touched_classes=()
    integration_classes=()
    while IFS= read -r file; do
      [[ -z "${file}" ]] && continue
      namespace_name="$(sed -nE 's/^namespace[[:space:]]+([A-Za-z0-9_.]+).*/\1/p' "${file}" | head -1)"
      [[ -z "${namespace_name}" ]] && namespace_name="KyberWeave.Tests"
      while IFS= read -r class_name; do
        if [[ "${file}" == tests/KyberWeave.Integration.Tests/*.cs ]]; then
          integration_classes+=("${namespace_name}.${class_name}")
        else
          touched_classes+=("${namespace_name}.${class_name}")
        fi
      done < <(grep -oE '^[[:space:]]*public[[:space:]]+(sealed[[:space:]]+|partial[[:space:]]+)*class[[:space:]]+[A-Za-z0-9_]+' "${file}" | awk '{print $NF}')
    done < <(printf '%s\n' "${touched_files[@]+"${touched_files[@]}"}" | sort -u)
    # The ceiling counts classes, not argv words: each integration class is named by a "-class" pair,
    # and counting the pairs doubled that half of the total and took the fast tier on a change inside it.
    touched_total=$(printf '%s\n' "${touched_classes[@]+"${touched_classes[@]}"}" "${integration_classes[@]+"${integration_classes[@]}"}" | sort -u | grep -c . || true)
    if [[ ${#touched_classes[@]} -gt 0 && ${touched_total} -le 40 ]]; then
      while IFS= read -r class; do
        test_args+=(-class "${class}")
      done < <(printf '%s\n' "${touched_classes[@]}" | sort -u)
      step "tests (touched: $(printf '%s\n' "${touched_classes[@]}" | sort -u | wc -l | tr -d ' ') classes)"
    elif [[ ${#touched_classes[@]} -gt 0 ]]; then
      printf 'fast-loop: --touched found %s test classes; running the fast tier instead.\n' "${touched_total}" >&2
      integration_classes=()
    fi
    integration_test_args=()
    while IFS= read -r class; do
      [[ -z "${class}" ]] && continue
      integration_test_args+=(-class "${class}")
    done < <(printf '%s\n' "${integration_classes[@]+"${integration_classes[@]}"}" | sort -u)
  fi

  if [[ ${#test_args[@]} -eq 0 && ${#integration_test_args[@]} -eq 0 ]]; then
    while IFS= read -r class || [[ -n "${class}" ]]; do
      class="${class%$'\r'}"
      [[ -z "${class}" || "${class}" == \#* ]] && continue
      test_args+=(-class "${class}")
    done < "${CLASS_LIST}"
    if [[ ${#test_args[@]} -eq 0 ]]; then
      printf 'no classes in %s; run --regenerate\n' "${CLASS_LIST}" >&2
      exit 1
    fi
    # The scale envelope is a size-stress test, not an edit check; keep it out even if its class
    # ever lands in the generated list.
    test_args+=(-trait- "Category=Scale")
    step "tests (fast tier: $(wc -l < "${CLASS_LIST}" | tr -d ' ') classes)"
  else
    step "tests (filtered)"
  fi

  # A filter that matches nothing exits 0, which reads as a pass, so read the runner's own total.
  # The class list and a --class / --method filter name classes in either test project, so the
  # policy project runs with the same arguments and the total is read across both.
  # Both runs always happen, so a product-suite failure cannot hide the policy results; the loop
  # fails after both, naming each exit status. pipefail makes a pipeline's status the runner's.
  test_log="$(mktemp "${TMPDIR:-/tmp}/kw-fast-loop.XXXXXX")"
  product_status=0
  integration_status=0
  policy_status=0
  run_product=1
  if [[ ${#test_args[@]} -eq 0 && ${#integration_test_args[@]} -gt 0 ]]; then
    # Only an integration class was touched: do not fall through to a full unit run.
    run_product=0
  fi
  if [[ "${run_product}" -eq 1 ]]; then
    dotnet "${TEST_DLL}" "${test_args[@]+"${test_args[@]}"}" | tee "${test_log}" || product_status=$?
  fi
  if [[ ${#integration_test_args[@]} -gt 0 ]]; then
    step "integration tests (touched)"
    dotnet "${INTEGRATION_TEST_DLL}" "${integration_test_args[@]}" | tee -a "${test_log}" || integration_status=$?
  fi
  if [[ "${needs_policy}" -eq 1 ]]; then
    step "repository-policy and prompt-content tests (same filter)"
    dotnet "${POLICY_TEST_DLL}" "${test_args[@]+"${test_args[@]}"}" | tee -a "${test_log}" || policy_status=$?
    dotnet "${PROMPT_TEST_DLL}" "${prompt_args[@]+"${prompt_args[@]}"}" | tee -a "${test_log}" || policy_status=$?
  else
    # Checked on its own: the product suite's total must not stand in for a scan run that matched nothing.
    step "repository-policy source scans"
    scan_log="$(mktemp "${TMPDIR:-/tmp}/kw-fast-loop-scans.XXXXXX")"
    dotnet "${POLICY_TEST_DLL}" "${POLICY_SOURCE_SCANS[@]}" | tee "${scan_log}" || policy_status=$?
    # A scan run that matched nothing is a policy failure, reported with the product status below.
    if [[ "${policy_status}" -eq 0 ]] && ! sed $'s/\x1b\\[[0-9;]*m//g' "${scan_log}" | grep -Eq 'Total: [1-9][0-9]*,'; then
      printf 'the policy source scans ran no tests; check POLICY_SOURCE_SCANS\n' >&2
      policy_status=1
    fi
  fi
  step "unit tests (Application, Hooks, Kernel, Mcp, Arbiter, Cli, Data, Architecture)"
  # The projects are independent and small, so they run at the same time. Each is its own background
  # process and its status comes back through `wait <pid>`: a variable set inside a backgrounded command
  # never reaches this shell, which is how a failing project would otherwise read as a pass.
  layers_status=0
  layer_pids=()
  layer_logs=()
  for layer_dll in "${LAYER_TEST_DLLS[@]}"; do
    layer_log="$(mktemp "${TMPDIR:-/tmp}/kw-fast-loop-layer.XXXXXX")"
    layer_logs+=("${layer_log}")
    dotnet "${layer_dll}" >"${layer_log}" 2>&1 &
    layer_pids+=($!)
  done
  for index in "${!layer_pids[@]}"; do
    layer_exit=0
    wait "${layer_pids[${index}]}" || layer_exit=$?
    cat "${layer_logs[${index}]}"
    rm -f "${layer_logs[${index}]}"
    if [[ "${layer_exit}" -ne 0 ]]; then
      layers_status="${layer_exit}"
    fi
  done
  if [[ "${product_status}" -ne 0 || "${integration_status}" -ne 0 || "${policy_status}" -ne 0 ]]; then
    if [[ "${integration_status}" -ne 0 ]]; then
      printf '\ntests failed: product suite exit %s, integration tests exit %s, repository-policy tests exit %s\n' \
        "${product_status}" "${integration_status}" "${policy_status}" >&2
    else
      printf '\ntests failed: product suite exit %s, repository-policy tests exit %s\n' \
        "${product_status}" "${policy_status}" >&2
    fi
    exit $(( product_status != 0 ? product_status : (integration_status != 0 ? integration_status : policy_status) ))
  fi
  if [[ "${layers_status}" -ne 0 ]]; then
    printf '\nlayer tests failed: exit %s\n' "${layers_status}" >&2
    exit "${layers_status}"
  fi
  if ! sed $'s/\x1b\\[[0-9;]*m//g' "${test_log}" | grep -Eq 'Total: [1-9][0-9]*,'; then
    printf 'no tests ran; check the --class / --method filter\n' >&2
    exit 1
  fi

  # Format and style are checked on the changed C# files only: the formatter loads and analyses the whole
  # solution either way, but verifying every file costs about a minute that a loop does not need. With no
  # changed file to name (a clean tree, or --class / --method), the whole solution is checked as before.
  # CI checks the whole solution, so a rule that reaches across files is still caught there.
  format_scope=()
  if [[ ${#changed_cs[@]} -gt 0 ]]; then
    format_scope=(--include "${changed_cs[@]}")
  fi
  step "format (whitespace${format_scope:+, changed files})"
  dotnet format KyberWeave.sln whitespace --verify-no-changes --no-restore -v minimal "${format_scope[@]+"${format_scope[@]}"}"
  step "format (style${format_scope:+, changed files})"
  dotnet format KyberWeave.sln style --verify-no-changes --no-restore -v minimal "${format_scope[@]+"${format_scope[@]}"}"
fi

if [[ "${needs_dash_server}" -eq 1 ]]; then
  step "kyberdash server build (Release, warnings-as-errors)"
  dotnet build dash/server/KyberDash.sln -c "${CONFIGURATION}"

  step "kyberdash server format (whitespace)"
  dotnet format dash/server/KyberDash.sln whitespace --verify-no-changes --no-restore -v minimal

  step "kyberdash server tests"
  dotnet test dash/server/KyberDash.sln -c "${CONFIGURATION}" --no-build
fi

if [[ "${needs_docs}" -eq 1 ]]; then
  step "docs validate (no CodeGraph index required)"
  if [[ "${needs_dotnet}" -eq 0 && ! -f "src/KyberWeave.Cli/bin/${CONFIGURATION}/net10.0/kyber-weave.dll" ]]; then
    step "build CLI for docs validate"
    dotnet build src/KyberWeave.Cli -c "${CONFIGURATION}"
  fi
  dotnet run --project src/KyberWeave.Cli -c "${CONFIGURATION}" --no-build -- \
    docs validate .
fi

if [[ "${needs_dash}" -eq 1 ]]; then
  step "dash typecheck"
  npm --prefix dash run typecheck

  step "dash lint"
  npm --prefix dash run lint

  if [[ ${#dash_related_files[@]} -gt 0 ]]; then
    step "dash tests (related: ${#dash_related_files[@]} files)"
    npm --prefix dash run test:related -- "${dash_related_files[@]}"
  fi

  if [[ "${needs_tray_ui}" -eq 1 ]]; then
    if [[ ! -d "dash/tray/ui/node_modules" ]]; then
      printf '\nError: dash/tray/ui/node_modules is missing. Run: npm --prefix dash/tray/ui ci\n' >&2
      exit 1
    fi
    step "tray ui typecheck"
    npm --prefix dash/tray/ui run typecheck

    step "tray ui test"
    npm --prefix dash/tray/ui run test
  fi
fi

if [[ "${needs_rust}" -eq 1 ]]; then
  step "tray rust (fmt, clippy, test)"
  (cd dash/tray/src-tauri && cargo fmt --check && cargo clippy -- -D warnings && cargo test)
fi

printf '\nFast tier clean. Push; CI runs the full suite.\n'
